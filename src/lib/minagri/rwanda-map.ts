/** Maps a free-text province name onto the five official names used by the map. */
export function matchProvince(raw: string): (typeof RWANDA_PROVINCES)[number]["name"] | null {
  const key = raw.toLowerCase().replace(/[^a-z]/g, "");
  if (!key) return null;
  if (key.includes("kigali")) return "Kigali City";
  if (key.includes("east")) return "Eastern Province";
  if (key.includes("west")) return "Western Province";
  if (key.includes("north")) return "Northern Province";
  if (key.includes("south")) return "Southern Province";
  return null;
}
